function formatTempC(temp) {
  if (typeof temp !== 'number' || !Number.isFinite(temp)) return '0.0 °C';
  const fixed = temp.toFixed(1);
  return temp > 0 ? `+${fixed} °C` : `${fixed} °C`;
}

// Преобразование RAW в массив объектов с объединением ВСЕХ 5 БЛЮД, ПЛОЩАДИ (км²), СОСЕДЕЙ и ТЕМПЕРАТУРЫ 2025
const DB = RAW.trim().replace(/\r/g, "").split("\n").map(l => {
  const p = l.split("|");
  const f = (p[5] || "").split(" — ");
  const code = p[1];

  // 1. Главное блюдо (из строки RAW)
  const mainFood = {
    name: f[0],
    desc: f[1] || "",
    isMain: true
  };

  // 2. Четыре блюда из EXTRA_FOODS
  const extras = (typeof EXTRA_FOODS !== 'undefined' && EXTRA_FOODS[code] ? EXTRA_FOODS[code] : []).map(item => ({
    name: item.name,
    desc: item.desc,
    isMain: false
  }));

  // 3. Собираем массив из 5 блюд
  const allFoods = [mainFood, ...extras];

  // 4. Площадь территории страны в км²
  const areaKm2 = (typeof COUNTRY_AREAS_KM2 !== 'undefined' && COUNTRY_AREAS_KM2[code] !== undefined)
    ? COUNTRY_AREAS_KM2[code]
    : 1000;

  // 5. Среднегодовая температура 2025 (°C)
  const tempVal = (typeof COUNTRY_TEMP_2025 !== 'undefined' && COUNTRY_TEMP_2025[code] !== undefined)
    ? COUNTRY_TEMP_2025[code]
    : 15.0;

  return {
    name: p[0],
    code: code,
    continent: CONT[p[2]],
    isUN: p[3][0] === "1",
    isMainland: p[3][1] === "1",
    capital: p[4],
    food: mainFood,       // 1 главное блюдо
    foods: allFoods,      // ВСЕ 5 БЛЮД
    population: +p[6],
    area: areaKm2,
    areaFormatted: formatAreaKm2(areaKm2),
    temp2025: tempVal,
    temp2025Formatted: formatTempC(tempVal),
    neighbors: [],
    neighborsCount: 0,
    neighborNames: [],
    regionsCount: +p[7],
    millionCitiesCount: +p[8],
    leader: p[9],
    mapSvg: MAPS[code] ? `<svg class="map" viewBox="0 0 100 100"><polygon points="${MAPS[code]}"/></svg>` : null
  };
});

// Симметричная привязка сухопутных соседей для всех 205 стран из DB
const COUNTRY_NEIGHBORS = {};
(() => {
  const validCodes = new Set(DB.map(c => c.code));
  const codeToCountry = {};
  DB.forEach(c => {
    codeToCountry[c.code] = c;
    COUNTRY_NEIGHBORS[c.code] = new Set();
  });

  Object.entries(COUNTRY_NEIGHBORS_RAW).forEach(([code, list]) => {
    if (!validCodes.has(code) || !Array.isArray(list)) return;
    list.forEach(nCode => {
      if (validCodes.has(nCode) && nCode !== code) {
        COUNTRY_NEIGHBORS[code].add(nCode);
        COUNTRY_NEIGHBORS[nCode].add(code);
      }
    });
  });

  DB.forEach(c => {
    const arr = Array.from(COUNTRY_NEIGHBORS[c.code] || []);
    arr.sort((a, b) => (codeToCountry[a]?.name || a).localeCompare(codeToCountry[b]?.name || b, 'ru'));
    COUNTRY_NEIGHBORS[c.code] = arr;
    c.neighbors = arr;
    c.neighborsCount = arr.length;
    c.neighborNames = arr.map(nCode => codeToCountry[nCode]?.name || nCode);
  });
})();

