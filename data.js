function formatAreaKm2(area) {
  if (typeof area !== 'number' || !Number.isFinite(area)) return '0 км²';
  if (area < 10 && !Number.isInteger(area)) {
    return `${area} км²`;
  }
  const rounded = Math.round(area);
  return `${rounded.toString().replace(/\B(?=(\d{3})+(?!\d))/g, ' ')} км²`;
}

